"""Run the pipeline on every evaluation/custom_cases/<case>/ mini dataset and score it against expected_output.csv.

Usage: python scripts/run_custom_cases.py      (writes evaluation/custom_cases/results.md and prints it)
Each case runs with its own root: its own CSVs, evidence index and workflow attribution; nothing leaks from
dataset/. Offline and deterministic (no OCR or LLM is needed by these cases).
"""
from __future__ import annotations

import csv
import io
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.audit.planner import plan_steps, to_steps_json  # noqa: E402
from app.audit.status import assess_case, build_context  # noqa: E402
from app.config import EVALUATION_DIR  # noqa: E402
from app.eval.scorer import read_rows, score  # noqa: E402
from app.eval.validate_output import HEADER, validate_rows  # noqa: E402
from app.ingest.loaders import load_requests  # noqa: E402

ROOT = EVALUATION_DIR / "custom_cases"


def run_case(d: Path) -> tuple[dict, dict, list[str]]:
    reqs = list(load_requests(d))
    ctx = build_context(reqs, root=d)
    pred = {}
    rows = []
    for r in reqs:
        a = assess_case(r, ctx)
        steps = plan_steps(a)
        pred[r.case_id] = (a.status, json.loads(to_steps_json(steps)))
        rows.append({"case_id": r.case_id, "deletion_status": a.status, "steps_json": to_steps_json(steps)})
    errors, _ = validate_rows(HEADER, rows, [r.case_id for r in reqs])
    return read_rows(d / "expected_output.csv"), pred, errors


def main() -> None:
    lines = ["# Custom evaluation cases: results", "",
             "Generated by `scripts/run_custom_cases.py`. Expected outputs were hand-written from the brief's rules "
             "(`scripts/make_custom_cases.py`) before running the pipeline.", "",
             "| case | tests | expected | predicted | steps matched | exact sequence | validator |",
             "|---|---|---|---|---|---|---|"]
    passed = 0
    details = []
    dirs = sorted(p for p in ROOT.iterdir() if p.is_dir())
    for d in dirs:
        exp, pred, errors = run_case(d)
        s = score(exp, pred)
        ok = s["status_accuracy"] == 1.0 and s["sequence_exact"] == 1.0 and not errors
        passed += ok
        cid = next(iter(exp))
        summary = (d / "README.md").read_text(encoding="utf-8").splitlines()[2][:90]
        lines.append(f"| {d.name} | {summary}... | {exp[cid][0]} | {pred[cid][0]} | {s['steps_matched']}/"
                     f"{s['steps_expected']} | {'yes' if s['sequence_exact'] == 1.0 else 'no'} | "
                     f"{'ok' if not errors else '; '.join(errors)} |")
        if not ok:
            details.append(f"\n### {d.name}\nexpected: {json.dumps(exp[cid][1])}\npredicted: {json.dumps(pred[cid][1])}")
    lines.append(f"\n**{passed}/{len(dirs)} custom cases pass** (status, exact step sequence and validator).")
    text = "\n".join(lines + details) + "\n"
    (ROOT / "results.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
